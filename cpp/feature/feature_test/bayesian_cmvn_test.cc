
#include "feature/bayesian_cmvn.h"
#include "tensor/tensor.h"
#include <memory>
#include <fstream>
#include <vector>

using namespace MERCURY;

bool measureLatencyAndError(std::shared_ptr<Tensor<float>> out, std::shared_ptr<Tensor<float>> target){
    std::shared_ptr<Tensor<float>> diff = std::make_shared<Tensor<float>>();
    diff->value = out->value - target->value;
    double rms_error = std::sqrt(diff->value.array().square().mean());
    if (rms_error > 1e-5){
        std::cout << "RMS ERROR Value is over 1e-5 ERROR Value: "<< rms_error << std::endl;
        return false;
    }
    std::cout << "[PASS!!] RMS ERROR IS SPEC IN: " << rms_error << std::endl;
    return true;
}

void test_bayesian_cmvn() {
    // Load test data from files generated by Python
    std::shared_ptr<Tensor<float>> mu0 = std::make_shared<Tensor<float>>();
    std::shared_ptr<Tensor<float>> std = std::make_shared<Tensor<float>>();
    std::shared_ptr<Tensor<float>> input = std::make_shared<Tensor<float>>();
    std::shared_ptr<Tensor<float>> expected_output = std::make_shared<Tensor<float>>();

    // Load values from .pt files
    std::vector<int> mu0_shape = {1, 10};
    std::vector<int> input_shape = {10, 10};
    
    mu0->loadValue("mu0.pt", mu0_shape);
    std->loadValue("std.pt", mu0_shape);
    input->loadValue("input.pt", input_shape);
    expected_output->loadValue("output.pt", input_shape);
    
    std::cout << "mu0: " << std::endl;
    mu0->printValue();
    std::cout << "std: " << std::endl;
    std->printValue();
    std::cout << "input: " << std::endl;
    input->printValue();

    // Create BayesianCMVNChunk instance
    BayesianCMVNChunk<float> cmvn(mu0, std);

    // Run normalization
    cmvn.reset();
    std::shared_ptr<Tensor<float>> output = cmvn.updateChunk(input);

    // Compare with expected output
    if (!measureLatencyAndError(output, expected_output)){
        expected_output->printValue();
        std::cout << "--------------------------------" << std::endl;
        output->printValue();
        std::cout << "Bayesian CMVN Test Failed" << std::endl;
    }
}


int main(int argc, char** argv) {
    test_bayesian_cmvn();
    return 0;
}
